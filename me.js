// ===== HAMBURGER MENU =====
function initHamburgerMenu() {
  const hamburger = document.querySelector(".hamburger");
  const navMobile = document.querySelector(".nav-mobile");
  const mobileLinks = navMobile.querySelectorAll("a");

  hamburger.addEventListener("click", () => {
    const isOpen = hamburger.classList.contains("active");
    hamburger.classList.toggle("active");
    navMobile.classList.toggle("active");
    hamburger.setAttribute("aria-expanded", !isOpen);
  });

  // Close menu when a link is clicked
  mobileLinks.forEach((link) => {
    link.addEventListener("click", () => {
      hamburger.classList.remove("active");
      navMobile.classList.remove("active");
      hamburger.setAttribute("aria-expanded", "false");
    });
  });

  // Close menu when clicking outside
  document.addEventListener("click", (e) => {
    if (!hamburger.contains(e.target) && !navMobile.contains(e.target)) {
      hamburger.classList.remove("active");
      navMobile.classList.remove("active");
      hamburger.setAttribute("aria-expanded", "false");
    }
  });
}

// ===== THEME TOGGLE =====
function initThemeToggle() {
  const themeToggle = document.querySelector(".theme-toggle");
  const html = document.documentElement;

  // Get saved theme or default to dark
  const savedTheme = localStorage.getItem("theme") || "dark";
  html.setAttribute("data-theme", savedTheme);

  themeToggle.addEventListener("click", () => {
    const currentTheme = html.getAttribute("data-theme");
    const newTheme = currentTheme === "dark" ? "light" : "dark";
    html.setAttribute("data-theme", newTheme);
    localStorage.setItem("theme", newTheme);
  });
}

// ===== LANGUAGE TOGGLE =====
function initLanguageToggle() {
  const langToggle = document.querySelector(".lang-toggle");
  const html = document.documentElement;
  const langDisplay = document.querySelector(".lang-text");

  // Get saved language or default to nl (Dutch)
  const savedLang = localStorage.getItem("language") || "nl";
  html.setAttribute("data-lang", savedLang);
  updateLanguageDisplay(savedLang);

  langToggle.addEventListener("click", () => {
    const currentLang = html.getAttribute("data-lang");
    const newLang = currentLang === "nl" ? "en" : "nl";
    html.setAttribute("data-lang", newLang);
    localStorage.setItem("language", newLang);
    updateLanguageDisplay(newLang);
    translatePage(newLang);
  });
}

function updateLanguageDisplay(lang) {
  const langDisplay = document.querySelector(".lang-text");
  langDisplay.textContent = lang === "nl" ? "EN" : "NL";
}

function translatePage(lang) {
  const elements = document.querySelectorAll("[data-i18n]");

  elements.forEach((el) => {
    const key = el.dataset.i18n;
    const translation = translations[lang]?.[key];

    if (translation) {
      // Special handling for elements with child spans
      if (el.querySelector("span") && key === "hero.title") {
        el.innerHTML = translation;
      } else {
        el.textContent = translation;
      }
    }
  });
}

// ===== SCROLL REVEAL =====
function initScrollReveal() {
  const revealItems = document.querySelectorAll(".reveal");
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible");
        }
      });
    },
    { threshold: 0.15 },
  );

  revealItems.forEach((item) => observer.observe(item));
}

// ===== ACCORDION =====
function initAccordion() {
  const accordions = document.querySelectorAll(".accordion");
  accordions.forEach((item) => {
    item.addEventListener("toggle", () => {
      if (item.open) {
        accordions.forEach((other) => {
          if (other !== item) other.open = false;
        });
      }
    });
  });
}

// ===== MOUSE GLOW =====
function initMouseGlow() {
  const glow = document.querySelector(".cursor-glow");
  if (!glow) return;

  // Only apply glow on non-touch devices
  const isTouchDevice = () =>
    window.matchMedia("(hover: none) and (pointer: coarse)").matches ||
    navigator.maxTouchPoints > 0;

  if (isTouchDevice()) {
    glow.style.display = "none";
    return;
  }

  window.addEventListener("mousemove", (e) => {
    glow.style.transform = `translate(${e.clientX - 140}px, ${e.clientY - 140}px)`;
  });
}

// ===== PORTRAIT 3D TILT =====
function initPortraitTilt() {
  const portrait = document.querySelector(".portrait-card");
  if (!portrait) return;

  // Only apply tilt on non-touch devices
  const isTouchDevice = () =>
    window.matchMedia("(hover: none) and (pointer: coarse)").matches ||
    navigator.maxTouchPoints > 0;

  if (isTouchDevice()) {
    return;
  }

  window.addEventListener("mousemove", (e) => {
    const x = (e.clientX / window.innerWidth - 0.5) * 8;
    const y = (e.clientY / window.innerHeight - 0.5) * 8;
    portrait.style.transform = `rotateY(${x * 0.35}deg) rotateX(${-y * 0.35}deg)`;
  });

  window.addEventListener("mouseleave", () => {
    portrait.style.transform = "";
  });
}

// ===== INIT ALL =====
document.addEventListener("DOMContentLoaded", () => {
  initHamburgerMenu();
  initThemeToggle();
  initLanguageToggle();
  initScrollReveal();
  initAccordion();
  initMouseGlow();
  initPortraitTilt();

  // Apply initial language
  const currentLang =
    document.documentElement.getAttribute("data-lang") || "nl";
  translatePage(currentLang);
});
